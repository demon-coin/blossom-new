//! RISC-V 64 用户内存原始字节拷贝与 32 位原子访存原语。
//!
//! # 模块职责与架构定位
//! 本模块位于 `arch::riscv64` 架构抽象层，向上为 `mm` 地址空间管理（如 `copyin`、`copyout`、
//! `load_user_u32`、`store_user_u32`）及 `futex` / 线程生命周期管理提供底层的跨页内字节拷贝与
//! 32 位 Acquire/Release 访存原语。
//!
//! # 核心设计与访存路径
//! 内核访问用户态内存时不依赖 RISC-V `sstatus.SUM` 位直接解引用用户虚拟地址，而是由上层 `Mm`
//! 先在软件中逐页校验用户权限、处理缺页/写时复制（COW）并持有物理页引用，再将目标页的**内核直接映射虚拟地址**
//! 传入本模块完成实际读写。
//!
//! 由于 RISC-V 64 硬件规范不保证未对齐的 8 字节宽访存（`ld`/`sd`）可由硬件直接完成（可能触发对齐异常或极慢的固件模拟），
//! `copy_user_bytes` 采用如下分阶段拷贝流水线：
//!
//! ```text
//! copy_user_bytes(dst, src, len) 执行路径:
//!
//!   len == 0 ──────────────────────────────────────────────> [Label 7: 直接返回]
//!      │
//!      ▼
//!   ((dst ^ src) & 7) == 0 ? (源与目标模 8 同余)
//!      ├─ 否 (异余) ───────────────────────────────────────> [Label 6/5: 逐字节 lbu/sb 循环]
//!      │
//!      └─ 是 (同余)
//!          ▼
//!      [Label 2: 首部对齐] 逐字节拷贝直到 (dst & 7) == 0
//!          ▼
//!      [Label 4: 宽字主循环] 只要 len >= 8，按 8 字节对齐执行 ld/sd
//!          ▼
//!      [Label 6/5: 尾部收敛] 剩余 0..7 字节按 lbu/sb 逐字节拷贝 ──> [Label 7: 返回]
//! ```
//!
//! # 锁获取顺序与并发契约
//! - 本模块纯汇编执行，不获取任何锁、不分配内存、不阻塞睡眠。
//! - 由于目标物理页可能同时被用户态线程或其他系统调用并发读写，本模块全程使用内联汇编直接操作裸指针，
//!   避免构造 Rust `&[u8]` 或 `&mut [u8]` 引用，从而防止并发修改违反 Rust 引用别名规则（Undefined Behavior）。

use core::arch::asm;

/// 在已锁住并完成权限检查的内核直映 RAM 地址之间按字节复制数据。
///
/// 供上层 `Mm` 在单页范围内执行用户态与内核态之间的数据拷贝。全程使用内联汇编完成，不分配内存、不睡眠，
/// 且不构造 Rust 共享或可变切片引用，允许底层共享页面存在并发的原始字节访问。
///
/// # Safety
/// 1. 当 `len > 0` 时，`src..src+len` 与 `dst..dst+len` 必须在整个调用期间指向有效、已映射的普通可缓存 RAM
///    （严禁指向 MMIO 设备内存），两个物理范围不得重叠，且 `src` 范围内的字节必须已初始化。
/// 2. 若一侧为普通内核缓冲区，目标端必须由当前调用方独占可写，源端必须满足只读借用约束；若一侧为用户态页面或页缓存共享页，
///    调用期間严禁任何代码对该范围持有冲突的 Rust 引用（`&T` / `&mut T`），且若目标页对其他并发读取者可见，目标页必须已完成零初始化或内容初始化。
/// 3. 涉及用户态页时，单次调用的访问范围必须完全落在同一个基本物理页内；上层 `Mm` 必须已完成对应方向（读/写）的权限检查、
///    写时复制（COW）拆分，并在调用返回前保持该物理页与内核直映关系存活，同时排除并发页面回收或设备 DMA 写入。
/// 4. 当 `len == 0` 时不解引用指针。
pub unsafe fn copy_user_bytes(dst: *mut u8, src: *const u8, len: usize) {
    // Step 1: 检查长度与源/目标地址的低 3 位对齐同余性。
    // Step 2: 若 `dst` 与 `src` 模 8 同余，先逐字节拷贝首部直至 8 字节对齐，再使用 `ld`/`sd` 每次拷贝 8 字节，最后逐字节处理不足 8 字节的尾部。
    // Step 3: 若 `dst` 与 `src` 模 8 不同余，全程退化为 `lbu`/`sb` 逐字节循环，避免触发 RISC-V 非对齐访存异常。
    // SAFETY:
    // 1. 调用方保证 `len > 0` 时 `src` 与 `dst` 在 `len` 字节内有效、不重叠、位于普通 RAM 且无冲突的 Rust 引用；
    // 2. 汇编在 `len == 0` 时于 `beqz {len}, 7f` 直接跳出，不发生任何解引用；
    // 3. 仅当 `(dst ^ src) & 7 == 0` 且首部逐字节推进至 `dst & 7 == 0`、同时剩余 `len >= 8` 时才执行 `ld`/`sd`，保证宽访存严格 8 字节对齐且不越界；
    // 4. `asm!` 未使用 `readonly` 或 `pure` 选项，编译器将其视为具有完整内存读写副作用的屏障。
    unsafe {
        asm!(
            "beqz {len}, 7f",
            "xor {tmp}, {dst}, {src}",
            "andi {tmp}, {tmp}, 7",
            "bnez {tmp}, 6f",
            "2:",
            "andi {tmp}, {dst}, 7",
            "beqz {tmp}, 4f",
            "lbu {tmp}, 0({src})",
            "sb {tmp}, 0({dst})",
            "addi {src}, {src}, 1",
            "addi {dst}, {dst}, 1",
            "addi {len}, {len}, -1",
            "beqz {len}, 7f",
            "j 2b",
            "4:",
            "sltiu {tmp}, {len}, 8",
            "bnez {tmp}, 6f",
            "ld {tmp}, 0({src})",
            "sd {tmp}, 0({dst})",
            "addi {src}, {src}, 8",
            "addi {dst}, {dst}, 8",
            "addi {len}, {len}, -8",
            "j 4b",
            "6:",
            "beqz {len}, 7f",
            "5:",
            "lbu {tmp}, 0({src})",
            "sb {tmp}, 0({dst})",
            "addi {src}, {src}, 1",
            "addi {dst}, {dst}, 1",
            "addi {len}, {len}, -1",
            "bnez {len}, 5b",
            "7:",
            dst = inout(reg) dst => _,
            src = inout(reg) src => _,
            len = inout(reg) len => _,
            tmp = out(reg) _,
            options(nostack),
        );
    }
}

/// 从已固定保活的用户页内核直映地址执行一次 32 位无符号整数的 Acquire 原子读取。
///
/// 供 `futex` 等待前比较用户态同步字、或读取用户态控制状态字时使用。
///
/// # Safety
/// 1. `src` 必须按 4 字节自然对齐，指向已初始化且完全位于单个基本物理页内的普通可缓存 RAM 内核直映地址。
/// 2. 上层 `Mm` 必须已验证用户态可读权限，并在本函数返回前保持底层物理页及映射存活。
/// 3. 调用期间严禁对该 4 字节范围持有可变 Rust 引用；并发的用户态或内核态写入必须使用兼容的 4 字节对齐原子操作。
pub unsafe fn load_user_u32(src: *const u32) -> u32 {
    let value: usize;
    // SAFETY:
    // 1. 调用方契约保证 `src` 4 字节对齐、已初始化且底层物理页在访问期间存活；
    // 2. 在 RV64 下，4 字节自然对齐的 `lwu` 是单次原子读取，随后的 `fence r, rw` 提供硬件 Acquire 内存序；
    // 3. `asm!` 默认声明内存副作用，阻止编译器将后续内存读写重排到本次读取之前。
    unsafe {
        asm!(
            "lwu {value}, 0({src})",
            "fence r, rw",
            src = in(reg) src,
            value = out(reg) value,
            options(nostack),
        );
    }
    value as u32
}

/// 向已固定保活的用户页内核直映地址执行一次 32 位无符号整数的 Release 原子写入。
///
/// 供线程退出时清零 `clear_child_tid`、唤醒前更新用户态同步字或测试同步门控时使用。
///
/// # Safety
/// 1. `dst` 必须按 4 字节自然对齐，指向完全位于单个基本物理页内的普通可缓存 RAM 内核直映地址。
/// 2. 上层 `Mm` 必须已验证用户态可写权限、完成必要的私有页写时复制（COW），并在本函数返回前保持底层物理页及映射存活。
/// 3. 调用期间严禁对该 4 字节范围持有任何 Rust 引用；需要观察此前内存副作用的并发读取方必须使用兼容的 Acquire 原子读取。
pub unsafe fn store_user_u32(dst: *mut u32, value: u32) {
    // SAFETY:
    // 1. 调用方契约保证 `dst` 4 字节对齐、具备可写权限且底层物理页在访问期间存活；
    // 2. 前置 `fence rw, w` 确保此前所有内存读写在本次写入前全局可见，4 字节自然对齐的 `sw` 执行单次原子写入，共同构成硬件 Release 语义；
    // 3. `asm!` 默认声明内存副作用，阻止编译器将此前的内存读写重排到本次写入之后。
    unsafe {
        asm!(
            "fence rw, w",
            "sw {value}, 0({dst})",
            dst = in(reg) dst,
            value = in(reg) value as usize,
            options(nostack),
        );
    }
}
