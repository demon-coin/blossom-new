//! 用户态特权级切换、寄存器现场保持、页表权限异常与虚拟内存（`Mm`）回归测试入口模块。
//!
//! # 模块职责与架构定位
//! 本模块汇总内核用户态执行与地址空间管理的核心 `ktest` 测试套件，负责向顶层测试注册表导出静态套件锚点。
//! - **上游调用者**：`crate::ktest::registry` 在构建测试目录与调度套件执行时引用 [`anchors`]。
//! - **下游依赖**：`crate::arch`（用户态进入/退出陷入路径与位置无关探测机器码）、`crate::mm`（硬件页表树 `UserPageTable`、
//!   地址空间 `Mm`、写时复制与用户态拷贝）、`crate::task::UserThread` 及 `crate::sched`。
//!
//! # 核心设计与套件划分
//! 由于 `#[ktest::suite]` 宏要求直接作用于模块定义上，本模块通过 `include!` 宏将两个测试套件内联到同一命名空间下，
//! 共享私有的测试夹具（[`fixture`]）与受控用户态探针工具（[`probe`]）：
//!
//! ```text
//! +-----------------------------------------------------------------------+
//! |                    ktest::user_execution 测试矩阵                     |
//! +-----------------------------------------------------------------------+
//! | 支撑子模块                                                            |
//! |   - fixture : 用户执行夹具 Users 与多任务阻塞同步控制器 Controls       |
//! |   - probe   : 受控用户地址空间构建 (CODE/DATA/STACK/TARGET) 与陷入辅助|
//! +-----------------------------------------------------------------------+
//! | 1. 用户态特权入口与硬件页表套件 (entry.rs -> entry)                   |
//! |   - 系统调用往返、浮点/向量寄存器保持、抢占与跨 CPU 迁移              |
//! |   - 奇偶页读写、未映射/PROT_NONE/只读写入/不可执行取指页故障          |
//! |   - UserPageTable 中间目录页预分配、叶子替换与延迟回收生命周期        |
//! +-----------------------------------------------------------------------+
//! | 2. 用户地址空间与虚拟内存套件 (vm.rs -> vm)                           |
//! |   - 按需匿名页首次触碰、fork 写时复制 (COW)、跨核活跃页表 TLB 同步    |
//! |   - copyin / copyout / C 字符串读取边界、睡眠读写锁与缺页并发互斥     |
//! +-----------------------------------------------------------------------+
//! ```
//!
//! # 锁获取顺序与并发契约
//! - 本文件仅组织子模块与编译期内联套件，自身不持有锁。
//! - 各内联套件均使用 `Users` 测试夹具，严格遵循 `set_up` -> `quiesce`（发出停止信号并等待全部子任务退出各自内核栈）
//!   -> `tear_down`（销毁测试对象并校验物理内存六域与工作队列元数据零泄漏）的三阶段生命周期。

mod fixture;
mod probe;

// `#[ktest::suite]` 宏作用于模块定义并据此生成套件全名与注册锚点；使用 `include!` 内联以保持路径并共享 `fixture` 与 `probe`。
include!("user_execution/entry.rs");
include!("user_execution/vm.rs");

/// 返回用户态执行测试模块下全部 2 个测试套件的静态注册槽引用数组。
///
/// 供上层 `ktest` 注册表显式引用，防止链接器在死代码消除（Dead Code Elimination）阶段丢弃由宏生成的静态套件描述符。
pub(crate) fn anchors() -> [&'static ::ktest::SuiteSlot; 2] {
    [entry::__ktest_anchor(), vm::__ktest_anchor()]
}
