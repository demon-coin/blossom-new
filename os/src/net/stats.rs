//! 网络接口收发流量与丢包统计快照定义。
//!
//! # 模块职责与架构定位
//! 本模块定义网络接口的累计流量计数器结构 [`InterfaceStats`]。
//! 下游由环回接口（`NetStack::loopback_stats`）与网卡驱动（[`crate::drivers::net_device::NetDevice`]）在报文收发及丢包路径上更新；
//! 上游供 `/proc/net/dev` 伪文件格式化器与内核测试通过 [`crate::net::NetStack::statistics`] 获取按值拷贝的统计快照。
//!
//! # 核心设计与统计维度
//!
//! ```text
//! InterfaceStats (8 x u64, 对应 /proc/net/dev 核心列):
//! +-----------------------+-----------------------------------------------+
//! | 接收方向 (RX)         | 发送方向 (TX)                                 |
//! +-----------------------+-----------------------------------------------+
//! | rx_bytes   (字节总数) | tx_bytes   (字节总数)                         |
//! | rx_packets (包/帧数)  | tx_packets (包/帧数)                          |
//! | rx_errors  (硬件错误) | tx_errors  (硬件错误)                         |
//! | rx_dropped (软件丢包) | tx_dropped (软件丢包)                         |
//! +-----------------------+-----------------------------------------------+
//! ```
//!
//! # 锁获取顺序与并发契约
//! - [`InterfaceStats`] 为实现 `Copy` 的纯数据结构，自身不包含锁。
//! - 环回接口的统计实例受 `NetStack::loopback_stats` 自旋锁保护；物理网卡的统计由驱动内部原子变量或自旋锁维护，读取时均直接返回完整值拷贝。

/// 网络接口接收（RX）与发送（TX）方向的 8 项累计统计计数。
///
/// 当前未单独监测底层物理层帧校验/对齐等硬件错误，因此 `rx_errors` 与 `tx_errors` 保持为 0。
#[derive(Clone, Copy, Debug, Default, Eq, PartialEq)]
pub struct InterfaceStats {
    /// 累计成功接收的字节总数（环回接口计 IP 报文长度，以太网计完整以太网帧长度；单位：字节）。
    pub rx_bytes: u64,
    /// 累计成功接收的报文或以太网帧总数（单位：个）。
    pub rx_packets: u64,
    /// 累计接收方向的硬件错误总数（当前固定为 0，单位：个）。
    pub rx_errors: u64,
    /// 累计接收方向因接收队列满、接口未启用或协议栈拒绝而丢弃的报文总数（单位：个）。
    pub rx_dropped: u64,
    /// 累计成功发送的字节总数（环回接口计 IP 报文长度，以太网计完整以太网帧长度；单位：字节）。
    pub tx_bytes: u64,
    /// 累计成功发送的报文或以太网帧总数（单位：个）。
    pub tx_packets: u64,
    /// 累计发送方向的硬件错误总数（当前固定为 0，单位：个）。
    pub tx_errors: u64,
    /// 累计发送方向因发送队列满或传输失败而丢弃的报文总数（单位：个）。
    pub tx_dropped: u64,
}
